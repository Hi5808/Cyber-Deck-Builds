#!/usr/bin/env python3
"""Validate sbc/catalog.csv and generate sbc/INDEX.md.

Usage:
    python3 tools/build_sbc_index.py

Exits with status 1 if the catalog has errors. No third-party dependencies.
"""

import csv
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SBC_DIR = ROOT / "sbc"
CATALOG = SBC_DIR / "catalog.csv"
INDEX = SBC_DIR / "INDEX.md"

COLUMNS = [
    "id", "family", "model", "soc", "ram_gb", "storage", "tier",
    "status", "acquired_from", "acquired_date", "deck", "notes",
]
TIERS = {"mcu", "entry", "mid", "high"}
STATUSES = {"owned", "in-deck", "spare", "for-sale", "gone"}


def families() -> set[str]:
    """Family names are the subfolders of sbc/ (hidden folders ignored)."""
    return {p.name for p in SBC_DIR.iterdir() if p.is_dir() and not p.name.startswith(".")}


def load_rows() -> list[dict]:
    with CATALOG.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != COLUMNS:
            sys.exit(f"error: catalog header must be: {','.join(COLUMNS)}")
        return list(reader)


def validate(rows: list[dict]) -> list[str]:
    errors = []
    known_families = families()
    seen_ids = set()
    for line, row in enumerate(rows, start=2):  # line 1 is the header
        where = f"catalog.csv line {line} ({row.get('id') or 'no id'})"
        if not row["id"]:
            errors.append(f"{where}: missing id")
        elif row["id"] in seen_ids:
            errors.append(f"{where}: duplicate id")
        seen_ids.add(row["id"])
        if row["family"] not in known_families:
            errors.append(f"{where}: unknown family '{row['family']}'")
        if row["tier"] not in TIERS:
            errors.append(f"{where}: tier must be one of {sorted(TIERS)}")
        if row["status"] not in STATUSES:
            errors.append(f"{where}: status must be one of {sorted(STATUSES)}")
        if row["status"] == "in-deck" and not row["deck"]:
            errors.append(f"{where}: status is in-deck but deck is empty")
        if row["acquired_date"] and not _is_iso_date(row["acquired_date"]):
            errors.append(f"{where}: acquired_date must be YYYY-MM-DD")
    return errors


def _is_iso_date(value: str) -> bool:
    from datetime import date
    try:
        date.fromisoformat(value)
        return True
    except ValueError:
        return False


def write_index(rows: list[dict]) -> None:
    active = [r for r in rows if r["status"] != "gone"]
    lines = [
        "# SBC Index",
        "",
        "_Generated by `tools/build_sbc_index.py`. Edit `catalog.csv` instead._",
        "",
        f"Total boards: **{len(rows)}** ({len(active)} not given away or sold)",
        "",
        "## Count by family",
        "",
        "| Family | Boards |",
        "|--------|--------|",
    ]
    by_family = Counter(r["family"] for r in active)
    for fam in sorted(families()):
        lines.append(f"| {fam} | {by_family.get(fam, 0)} |")

    lines += ["", "## Count by status", "", "| Status | Boards |", "|--------|--------|"]
    by_status = Counter(r["status"] for r in rows)
    for st in sorted(STATUSES):
        lines.append(f"| {st} | {by_status.get(st, 0)} |")

    lines += ["", "## All boards", ""]
    if rows:
        lines += [
            "| ID | Family | Model | SoC | RAM (GB) | Tier | Status | Deck |",
            "|----|--------|-------|-----|----------|------|--------|------|",
        ]
        for r in sorted(rows, key=lambda r: (r["family"], r["model"], r["id"])):
            lines.append(
                f"| {r['id']} | {r['family']} | {r['model']} | {r['soc']} | "
                f"{r['ram_gb']} | {r['tier']} | {r['status']} | {r['deck']} |"
            )
    else:
        lines.append("_No boards in the catalog yet._")
    lines.append("")
    INDEX.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    rows = load_rows()
    errors = validate(rows)
    if errors:
        print("Catalog has errors:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1
    write_index(rows)
    print(f"Validated {len(rows)} board(s); wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
